static uint8_t g_byte6ef = 0xb0;                 // last SET 0xEF byte[6]; echoed in GET 0xEF/0xF8 byte[7]
static uint8_t g_masterBd[6];                    // host MAC learned via SET 0xF5
static bool g_haveMaster;
// Controller BT MAC (OUI 00:1B:DC like the other PS modes; last byte 0x80 keeps
// it distinct). Only relevant to BT pairing identity; read via GET 0xF2.
static const uint8_t g_ds3Mac[6] = { 0x00, 0x1B, 0xDC, 0x4F, 0x55, 0x80 };

// Copy a 64-byte Sixaxis feature report verbatim (raw TinyUSB does not prepend
// the id). Returns min(64, reqlen).
static uint16_t emit_feature(uint8_t *buf, uint16_t reqlen, const uint8_t arr[64])
{
	uint16_t n = reqlen < 64 ? reqlen : 64;
	memcpy(buf, arr, n);
	return n;
}

static uint16_t ds3_get(int slot, uint8_t rid, uint8_t type, uint8_t *buf,
			uint16_t reqlen)
{
	(void)slot;
	if (type != PP_HID_FEATURE || !buf || reqlen == 0)
		return 0;
	uint8_t r[64];
	switch (rid) {
	case 0x01:
		return emit_feature(buf, reqlen, report_01);
	case 0xf2:  // overlay our controller MAC at [4..9]
		memcpy(r, report_f2, 64);
		memcpy(r + 4, g_ds3Mac, 6);
		return emit_feature(buf, reqlen, r);
	case 0xf5:  // overlay learned host MAC at [2..7]
		memcpy(r, report_f5, 64);
		if (g_haveMaster)
			memcpy(r + 2, g_masterBd, 6);
		return emit_feature(buf, reqlen, r);
	case 0xef:  // echo the PS3's remembered byte at [7]
		memcpy(r, report_ef, 64);
		r[7] = g_byte6ef;
		return emit_feature(buf, reqlen, r);
	case 0xf8:
		memcpy(r, report_f8, 64);
		r[7] = g_byte6ef;
		return emit_feature(buf, reqlen, r);
	case 0xf7:
		return emit_feature(buf, reqlen, report_f7);
	default:
		return 0;
	}
}

static void ds3_set(int slot, uint8_t rid, uint8_t type, const uint8_t *b,
		    uint16_t n)
{
	if (type == PP_HID_FEATURE) {
		// 0xEF: remember byte[6] for the next GET echo. 0xF5: learn host MAC.
		// 0xF4 (set-operational) is ACKed silently — we stream unconditionally.
		if (rid == 0xef && n >= 7)
			g_byte6ef = b[6];
		else if (rid == 0xf5 && n >= 8) {
			memcpy(g_masterBd, b + 2, 6);
			g_haveMaster = true;
		}
		return;
	}
	if (type != PP_HID_OUTPUT)
		return;
	// OUT endpoint delivers rid=0 with the id in b[0]; control SET_REPORT splits
	// the id into rid. Normalise to p = bytes AFTER the id.
	const uint8_t *p;
	uint16_t pn;
	if (rid == 0) {
		if (n < 1 || b[0] != 0x01) return;
		p = b + 1; pn = (uint16_t)(n - 1);
	} else if (rid == 0x01) {
		p = b; pn = n;
	} else {
		return;
	}
	if (pn < 5)
		return;
	// Output report 0x01 body: p[0]=0x00, p[1]=small dur, p[2]=small power,
	// p[3]=large dur, p[4]=large power. Large→lowFreq, small→highFreq(on/off);
	// 257 = 65535/255 scales 8-bit power to the 16-bit haptic range.
	puck_rumble(slot, (uint16_t)p[4] * 257u, p[2] ? 0xFFFFu : 0u);
}

// SC2 IMU int16 (center 0) → DS3 10-bit unsigned (center 511), little-endian.
static void ds3_imu(uint8_t *out, int16_t v)
{
	int32_t e = 511 + ((int32_t)v >> 6);
	if (e < 0) e = 0;
	if (e > 1023) e = 1023;
	out[0] = (uint8_t)(e & 0xFF);
	out[1] = (uint8_t)((e >> 8) & 0xFF);
}

// Build the 48-byte input payload (id 0x01 prepended by the stack → 49-byte
// Sixaxis report). Offsets are the genuine report's rd[] minus one.
static uint16_t ds3_build(int slot, uint8_t *out, uint8_t *rid)
{
	*rid = 0x01;
	uint32_t b = g_in[slot].buttons;
	bool l2 = (g_in[slot].lt > SW_TRIG_ON) || (b & TB_L2);
	bool r2 = (g_in[slot].rt > SW_TRIG_ON) || (b & TB_R2);
	memset(out, 0, 48);

	// out[1]: Select L3 R3 Start Up Right Down Left. SC2 View→Start, Menu→Select
	// (matches the physical button positions on the puck).
	out[1] = ((b & TB_MENU) ? 0x01 : 0) | ((b & TB_L3) ? 0x02 : 0) |
		 ((b & TB_R3) ? 0x04 : 0) | ((b & TB_VIEW) ? 0x08 : 0) |
		 ((b & TB_DUP) ? 0x10 : 0) | ((b & TB_DRT) ? 0x20 : 0) |
		 ((b & TB_DDN) ? 0x40 : 0) | ((b & TB_DLF) ? 0x80 : 0);

	// out[2]: L2 R2 L1 R1 Triangle Circle Cross Square.
	uint8_t tri = (b & TB_Y) ? 0x10 : 0;
	uint8_t cir = (b & TB_B) ? 0x20 : 0;
	uint8_t crs = (b & TB_A) ? 0x40 : 0;
	uint8_t sqr = (b & TB_X) ? 0x80 : 0;
	out[2] = (l2 ? 0x01 : 0) | (r2 ? 0x02 : 0) | ((b & TB_LB) ? 0x04 : 0) |
		 ((b & TB_RB) ? 0x08 : 0) | tri | cir | crs | sqr;

	out[3] = (b & TB_STEAM) ? 0x01 : 0;  // PS button

	out[5] = sw_stick(g_in[slot].lx, false);
	out[6] = sw_stick(g_in[slot].ly, true);
	out[7] = sw_stick(g_in[slot].rx, false);
	out[8] = sw_stick(g_in[slot].ry, true);

	// out[13..24]: analog pressures Up Right Down Left L2 R2 L1 R1 Tri Cir Crs Sqr.
	out[13] = (b & TB_DUP) ? 0xFF : 0;
	out[14] = (b & TB_DRT) ? 0xFF : 0;
	out[15] = (b & TB_DDN) ? 0xFF : 0;
	out[16] = (b & TB_DLF) ? 0xFF : 0;
	out[17] = g_in[slot].lt;
	out[18] = g_in[slot].rt;
	out[19] = (b & TB_LB) ? 0xFF : 0;
	out[20] = (b & TB_RB) ? 0xFF : 0;
	out[21] = tri ? 0xFF : 0;
	out[22] = cir ? 0xFF : 0;
	out[23] = crs ? 0xFF : 0;
	out[24] = sqr ? 0xFF : 0;

	out[28] = 0x00;
	out[29] = 0x05;  // battery level: full (cosmetic over USB)

	// out[40..47]: accel X, accel Z, accel Y, gyro Z — each 10-bit LE, center 511.
	ds3_imu(out + 40, g_in[slot].ax);
	ds3_imu(out + 42, g_in[slot].az);
	ds3_imu(out + 44, g_in[slot].ay);
	ds3_imu(out + 46, g_in[slot].gz);
	return 48;
}

